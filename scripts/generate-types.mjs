import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const project = new URL('../src/PhoneticAnnotator.Wasm/', import.meta.url);
const sourcePath = new URL('Interop.cs', project);
const outputPath = new URL('PhoneticAnnotator.d.ts', project);

export function generateDeclarations(source) {
    const code = source.replace(/\/\*[\s\S]*?\*\/|\/\/[^\r\n]*/g, '');
    const namespace = code.match(/\bnamespace\s+([\w.]+)\s*;/)?.[1];
    const className = code.match(/\bpublic\s+static\s+partial\s+class\s+(\w+)/)?.[1];
    if (!namespace || !className) throw new Error('Expected a file-scoped namespace and public static partial class.');
    const exports = [];
    const names = new Set();
    const types = new Map([['string', 'string'], ['byte[]', 'Uint8Array']]);
    for (const attribute of code.matchAll(/\[(?:[\w.]+\.)?JSExport(?:Attribute)?\b[^\]]*\]/g)) {
        if (!/^\[(?:[\w.]+\.)?JSExport(?:Attribute)?(?:\(\))?\]$/.test(attribute[0])) {
            throw new Error(`Unsupported export attribute: ${attribute[0]}`);
        }
        const tail = code.slice(attribute.index + attribute[0].length);
        const signature = tail.match(/^\s*public\s+static\s+(?:async\s+)?(Task(?:<string>)?)\s+(\w+)\s*\(([^)]*)\)\s*(?:=>|\{)/);
        if (!signature) throw new Error(`Unsupported [JSExport] signature: ${tail.trim().split('\n')[0]}`);
        const [, returnType, name, parameters] = signature;
        if (names.has(name)) throw new Error(`Overloaded exports are unsupported: ${name}`);
        names.add(name);
        const args = parameters.trim() ? parameters.split(',').map(parameter => {
            const match = parameter.trim().match(/^(\S+)\s+([A-Za-z_]\w*)$/);
            if (!match || !types.has(match[1])) throw new Error(`Unsupported parameter in ${name}: ${parameter.trim()}`);
            return `${match[2]}: ${types.get(match[1])}`;
        }) : [];
        exports.push(`    ${name}(${args.join(', ')}): Promise<${returnType === 'Task' ? 'void' : 'string'}>;`);
    }
    if (!exports.length) throw new Error('No [JSExport] methods found.');
    return `// Generated by scripts/generate-types.mjs from Interop.cs. Do not edit.
// byte[] uses the .NET JS interop Uint8Array binding.

/** exports.${namespace}.${className} from getAssemblyExports(). */
export interface PhoneticAnnotatorInterop {
${exports.join('\n')}
}

/** The nested object returned by getAssemblyExports("PhoneticAnnotator.Wasm"). */
export interface PhoneticAnnotatorAssemblyExports {
    ${namespace.split('.').join(': { ')}: { ${className}: PhoneticAnnotatorInterop ${'}'.repeat(namespace.split('.').length)};
}

export interface WorkerInitializeOptions {
    /** dotnet.js URL, relative to the worker script. Defaults to ./_framework/dotnet.js. */
    runtimeUrl?: string;
}

export interface PhoneticAnnotatorWorkerMethods extends PhoneticAnnotatorInterop {
    /** Starts once; calls without initialize use the default URL. Cannot change URL after startup. */
    initialize(options?: WorkerInitializeOptions): Promise<void>;
}

export type WorkerRequestId = string | number;
export type WorkerMethod = keyof PhoneticAnnotatorWorkerMethods;
/** IDs must be unique among pending calls. Messages are executed in arrival order. */
export type WorkerRequest<M extends WorkerMethod = WorkerMethod> = {
    [K in M]: { id: WorkerRequestId; method: K; args: Parameters<PhoneticAnnotatorWorkerMethods[K]> }
}[M];
export interface WorkerError { name: string; message: string; }
export type WorkerResponse<M extends WorkerMethod = WorkerMethod> =
    | { id: WorkerRequestId; ok: true; result: Awaited<ReturnType<PhoneticAnnotatorWorkerMethods[M]>> }
    | { id: WorkerRequestId | null; ok: false; error: WorkerError };
/** Ready is emitted once after Main completes and onReady has fired; startup failures are sticky. */
export type WorkerEvent =
    | { type: 'ready' }
    | { type: 'startup-error'; error: WorkerError };
export type WorkerMessage = WorkerResponse | WorkerEvent;
`;
}

export async function main(args = process.argv.slice(2)) {
    if (args.some(arg => arg !== '--check') || args.length > 1) throw new Error('Usage: node scripts/generate-types.mjs [--check]');
    const expected = generateDeclarations(await readFile(sourcePath, 'utf8'));
    if (args.includes('--check')) {
        let current;
        try { current = await readFile(outputPath, 'utf8'); }
        catch (error) { if (error.code !== 'ENOENT') throw error; }
        if (current !== expected) throw new Error('PhoneticAnnotator.d.ts is stale. Run node scripts/generate-types.mjs.');
    } else {
        await writeFile(outputPath, expected);
    }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
